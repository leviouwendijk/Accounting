import Accounting
import AccountingCompiler
import Foundation
import TestFlows
import Writers

extension AccountingTestFlowsSuite {
    static var exampleDepreciationWriterFlow: TestFlow {
        TestFlow("accounting-example-depreciation-writer", tags: ["accounting", "example", "depreciation", "writer"]) {
            Step("April writer posts once and subsequent runs preserve the ledger") {
                let packageRoot = URL(fileURLWithPath: #filePath)
                    .deletingLastPathComponent().deletingLastPathComponent()
                    .deletingLastPathComponent().deletingLastPathComponent()
                let exampleRoot = packageRoot.appendingPathComponent(
                    "Testing/accounting-example", isDirectory: true
                )

                // Writer tests must never mutate the version-controlled example.
                let fm = FileManager.default
                let scratch = fm.temporaryDirectory.appendingPathComponent(
                    "accounting-depreciation-writer-\(UUID().uuidString)", isDirectory: true
                )
                try fm.createDirectory(at: scratch, withIntermediateDirectories: true)
                defer { try? fm.removeItem(at: scratch) }
                let projectRoot = scratch.appendingPathComponent("project", isDirectory: true)
                try fm.copyItem(at: exampleRoot, to: projectRoot)

                var calendar = Calendar(identifier: .gregorian)
                let timezone = TimeZone(identifier: "Europe/Amsterdam")!
                calendar.timeZone = timezone
                let aprilStart = calendar.date(from: DateComponents(year: 2026, month: 4, day: 1))!
                let mayStart = calendar.date(from: DateComponents(year: 2026, month: 5, day: 1))!
                let generated = projectRoot.appendingPathComponent(
                    "entries/2026/2/4/depreciation.ec"
                )
                let safe = SafeWriteOptions(
                    existingFilePolicy: .overwrite,
                    makeBackupOnOverride: false,
                    whitespaceOnlyIsBlank: false,
                    backupSuffix: "_previous_version.bak"
                )

                let first = try DepreciationAuditRunner.writeMissingForMonth(
                    monthStart: aprilStart,
                    projectRoot: projectRoot,
                    tz: timezone,
                    tolerance: 0,
                    safe: safe
                )
                try Expect.equal(first, 1, "example.writer-first-creates-one-entry")
                try Expect.true(fm.fileExists(atPath: generated.path), "example.writer-generated-month-path")
                let firstBytes = try Data(contentsOf: generated)
                let firstText = String(decoding: firstBytes, as: UTF8.self)
                try Expect.equal(
                    firstText.components(separatedBy: "entry {").count - 1,
                    1, "example.writer-one-entry-in-file"
                )
                try Expect.true(firstText.contains("debit = 20.00"), "example.writer-amount-debit")
                try Expect.true(firstText.contains("credit = 20.00"), "example.writer-amount-credit")

                let second = try DepreciationAuditRunner.writeMissingForMonth(
                    monthStart: aprilStart,
                    projectRoot: projectRoot,
                    tz: timezone,
                    tolerance: 0,
                    safe: safe
                )
                try Expect.equal(second, 0, "example.writer-second-creates-nothing")
                try Expect.equal(
                    try Data(contentsOf: generated), firstBytes,
                    "example.writer-second-preserves-file-bytes"
                )

                // An April-scoped audit must be fully reconciled; later months
                // remain intentionally unposted in the example.
                let report = try DepreciationAuditRunner.run(
                    projectRoot: projectRoot,
                    through: mayStart.addingTimeInterval(-1),
                    options: .init(granularity: .monthly, tolerance: 0, calendar: calendar)
                )
                try Expect.equal(report.items.count, 1, "example.writer-april-audit-slice")
                guard let item = report.items.first else {
                    try Expect.true(false, "example.writer-april-audit-present")
                    return
                }
                try Expect.equal(item.expected, Decimal(20), "example.writer-april-expected")
                try Expect.equal(item.actual, Decimal(20), "example.writer-april-posted")
                try Expect.equal(item.actualAutoGenerated, Decimal(20), "example.writer-april-auto-generated")
                try Expect.equal(item.delta, Decimal(0), "example.writer-april-zero-deficit")
                try Expect.equal(item.coverage.rawValue, "exact", "example.writer-april-exact")
            }
        }
    }
}
